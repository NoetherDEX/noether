-- Pre-Supabase web leaderboard baseline (one-time import from the retired
-- Vercel-cron Turso DB; rows before the 2026-07-06T17:00Z prod cutover).
-- total_volume / total_pnl are stored in 7-decimal integer units — the
-- import script scales the legacy USD floats by 1e7 so this table merges
-- with live stats without unit conversion at read time.
CREATE TABLE IF NOT EXISTS leaderboard_legacy (
  address       TEXT PRIMARY KEY,
  trade_count   BIGINT  NOT NULL DEFAULT 0,
  total_volume  NUMERIC NOT NULL DEFAULT 0,
  total_pnl     NUMERIC NOT NULL DEFAULT 0,
  liq_count     BIGINT  NOT NULL DEFAULT 0,
  source        TEXT    NOT NULL DEFAULT 'web-turso-2026-07',
  imported_at   BIGINT  NOT NULL
);
