  hwm_nav            NUMERIC NOT NULL DEFAULT 10000000,
  realized_pnl       NUMERIC NOT NULL DEFAULT 0,
  leader_shares      NUMERIC NOT NULL DEFAULT 0,
  profit_share_bps   INTEGER NOT NULL DEFAULT 1000,
  paused             SMALLINT NOT NULL DEFAULT 0,
  updated_at         BIGINT NOT NULL,
  contract_id        TEXT
);

