-- Postgres baseline (Supabase migration, 2026-07).
--
-- Consolidates the retired SQLite migrations 001–017 into the current
-- schema. History: one-shot data fixes (006–009) and backfills (010/011)
-- are gone — data arrives via scripts/migrate-turso-to-supabase. Dead
-- tables positions_cache / orders_cache (schema-only since 001, zero
-- readers/writers — audit 2026-06 §340) are not carried over.
--
-- Type conventions (see docs/BACKUP_RESTORE.md):
--   * ledgers / unix timestamps / ids     → BIGINT
--     (api_keys.*_at are MILLISECONDS, event timestamps are seconds)
--   * chain i128 quantities written via .toString() and read via
--     BigInt(String(x)) / Number(x)       → TEXT (byte-parity with libsql)
--   * accumulators mutated in SQL (x=x+?) → NUMERIC (vaults, referrers)
--   * flags written as 0/1               → SMALLINT (vaults.paused)
--   * event payloads                     → JSONB, but ALWAYS read back as a
--     raw string (@noether/db pins json/jsonb type parsers to identity)
--
-- The runner executes one statement at a time: keep `--# split` between
-- statements (extended-protocol queries cannot batch statements).

CREATE TABLE IF NOT EXISTS poll_cursor (
  id                    INTEGER PRIMARY KEY CHECK (id = 1),
  last_ledger           BIGINT NOT NULL,
  last_pagination_token TEXT,
  updated_at            BIGINT NOT NULL
);

